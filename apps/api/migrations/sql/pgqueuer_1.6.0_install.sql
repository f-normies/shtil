-- pgqueuer 1.6.0 -- prefix='' schema='pgq' durability=durable

CREATE SCHEMA IF NOT EXISTS pgq;

CREATE TYPE pgq.pgqueuer_status AS ENUM ('queued', 'picked', 'successful', 'exception', 'canceled', 'deleted', 'failed');

CREATE TABLE pgq.pgqueuer (
    id bigserial NOT NULL PRIMARY KEY,
    priority integer NOT NULL,
    queue_manager_id uuid,
    created timestamp with time zone NOT NULL DEFAULT now(),
    updated timestamp with time zone NOT NULL DEFAULT now(),
    heartbeat timestamp with time zone NOT NULL DEFAULT now(),
    execute_after timestamp with time zone NOT NULL DEFAULT now(),
    status pgq.pgqueuer_status NOT NULL,
    entrypoint text NOT NULL,
    dedupe_key text,
    payload bytea,
    headers jsonb,
    attempts integer NOT NULL DEFAULT 0,
    slot bigint
);

CREATE TABLE pgq.pgqueuer_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    created timestamp with time zone NOT NULL DEFAULT now(),
    job_id bigint NOT NULL,
    status pgq.pgqueuer_status NOT NULL,
    priority integer NOT NULL,
    entrypoint text NOT NULL,
    traceback jsonb,
    aggregated boolean DEFAULT false
);

CREATE TABLE pgq.pgqueuer_schedules (
    id bigserial NOT NULL PRIMARY KEY,
    expression text NOT NULL,
    entrypoint text NOT NULL,
    heartbeat timestamp with time zone NOT NULL DEFAULT now(),
    created timestamp with time zone NOT NULL DEFAULT now(),
    updated timestamp with time zone NOT NULL DEFAULT now(),
    next_run timestamp with time zone NOT NULL DEFAULT now(),
    last_run timestamp with time zone,
    status pgq.pgqueuer_status DEFAULT 'queued'::pgq.pgqueuer_status,
    UNIQUE (expression, entrypoint)
);

CREATE TABLE pgq.pgqueuer_statistics (
    id bigserial NOT NULL PRIMARY KEY,
    created timestamp with time zone NOT NULL DEFAULT date_trunc('sec'::text, now()),
    count bigint NOT NULL,
    priority integer NOT NULL,
    status pgq.pgqueuer_status NOT NULL,
    entrypoint text NOT NULL
);

CREATE INDEX pgqueuer_ep_ea_idx ON pgq.pgqueuer USING btree (entrypoint, execute_after) WHERE (status = 'queued'::pgq.pgqueuer_status);

CREATE INDEX pgqueuer_ep_prio_id_idx ON pgq.pgqueuer USING btree (entrypoint, priority DESC, id) WHERE (status = 'queued'::pgq.pgqueuer_status);

CREATE INDEX pgqueuer_log_created ON pgq.pgqueuer_log USING btree (created);

CREATE INDEX pgqueuer_log_job_id_status ON pgq.pgqueuer_log USING btree (job_id, created DESC);

CREATE INDEX pgqueuer_log_not_aggregated ON pgq.pgqueuer_log USING btree ((1)) WHERE (NOT aggregated);

CREATE INDEX pgqueuer_log_status ON pgq.pgqueuer_log USING btree (status);

CREATE INDEX pgqueuer_picked_heartbeat_idx ON pgq.pgqueuer USING btree (heartbeat) WHERE (status = 'picked'::pgq.pgqueuer_status);

CREATE UNIQUE INDEX pgqueuer_picked_slot_idx ON pgq.pgqueuer USING btree (entrypoint, slot) WHERE ((status = 'picked'::pgq.pgqueuer_status) AND (slot IS NOT NULL));

CREATE INDEX pgqueuer_priority_id_id1_idx ON pgq.pgqueuer USING btree (priority, id DESC) INCLUDE (id) WHERE (status = 'queued'::pgq.pgqueuer_status);

CREATE INDEX pgqueuer_queue_manager_id_idx ON pgq.pgqueuer USING btree (queue_manager_id) WHERE (queue_manager_id IS NOT NULL);

CREATE UNIQUE INDEX pgqueuer_statistics_unique_count ON pgq.pgqueuer_statistics USING btree (priority, date_trunc('sec'::text, timezone('UTC'::text, created)), status, entrypoint);

CREATE UNIQUE INDEX pgqueuer_unique_dedupe_key ON pgq.pgqueuer USING btree (dedupe_key) WHERE ((status = ANY (ARRAY['queued'::pgq.pgqueuer_status, 'picked'::pgq.pgqueuer_status])) AND (dedupe_key IS NOT NULL));

CREATE INDEX pgqueuer_updated_id_id1_idx ON pgq.pgqueuer USING btree (updated, id DESC) INCLUDE (id) WHERE (status = 'picked'::pgq.pgqueuer_status);

CREATE FUNCTION pgq.fn_pgqueuer_changed() RETURNS TRIGGER AS $$
DECLARE
    to_emit BOOLEAN := false;  -- Flag to decide whether to emit a notification
BEGIN
    -- Check operation type and set the emit flag accordingly
    IF TG_OP = 'UPDATE' AND OLD IS DISTINCT FROM NEW THEN
        to_emit := true;
    ELSIF TG_OP = 'DELETE' THEN
        to_emit := true;
    ELSIF TG_OP = 'INSERT' THEN
        to_emit := true;
    ELSIF TG_OP = 'TRUNCATE' THEN
        to_emit := true;
    END IF;

    -- Perform notification if the emit flag is set
    IF to_emit THEN
        PERFORM pg_notify(
            'ch_pgqueuer',
            json_build_object(
                'channel', 'ch_pgqueuer',
                'operation', lower(TG_OP),
                'sent_at', NOW(),
                'table', TG_TABLE_NAME,
                'type', 'table_changed_event'
            )::text
        );
    END IF;

    -- Return appropriate value based on the operation
    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        RETURN NEW;
    ELSIF TG_OP = 'DELETE' THEN
        RETURN OLD;
    ELSE
        RETURN NULL; -- For TRUNCATE and other non-row-specific contexts
    END IF;

END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_pgqueuer_changed
AFTER INSERT OR UPDATE OR DELETE OR TRUNCATE ON pgq.pgqueuer
EXECUTE FUNCTION pgq.fn_pgqueuer_changed();
