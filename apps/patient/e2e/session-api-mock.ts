import type { Schemas } from "@compass/api-client";
import type { BrowserContext, Route } from "@playwright/test";
import { DEFINITION_V1, PATIENT_A, SUBMISSION_A } from "./assessment-fixtures";

export type Role = Schemas["UserOut"]["role"];
export type ApiCall = { method: string; path: string; pagePath: string };
export type AssessmentSubmissionResponse = { submissionId: string; status: number | null };

/** Пустая сводка для сценариев, которые проверяют другие разделы карточки. */
export function emptyVisitSummary(): Schemas["VisitSummaryOut"] {
  return {
    id: null,
    status: "empty",
    period_start: "2026-10-01T00:00:00Z",
    period_end: null,
    stale: false,
    facts: [],
    statements: [],
    edited: false,
    confirmed_by: null,
    confirmed_by_name: null,
    confirmed_at: null,
  };
}

const USER_ID = "00000000-0000-4000-8000-0000000000d1";

export function user(role: Role, patientId = PATIENT_A): Schemas["UserOut"] {
  return {
    id: role === "patient" ? patientId : USER_ID,
    email: `${role}@example.invalid`,
    role,
    full_name: `Синтетический ${role}`,
  };
}

function json(route: Route, status: number, body: unknown): Promise<void> {
  return route.fulfill({ status, contentType: "application/json", body: JSON.stringify(body) });
}

function expired(route: Route): Promise<void> {
  return json(route, 401, { status: 401, title: "Сессия завершена" });
}

/** A step the mock waits for: `reached` marks it started, `release` lets it finish. */
type Gate = {
  started: Promise<void>;
  release: () => void;
  reached: () => void;
  open: Promise<void>;
};

function createGate(): Gate {
  let reached: () => void = () => {};
  let release: () => void = () => {};
  const started = new Promise<void>((resolve) => {
    reached = resolve;
  });
  const open = new Promise<void>((resolve) => {
    release = resolve;
  });
  return { started, release, reached, open };
}

/** Synthetic session API for both cabinets; every reply is generated by the test. */
export async function mockSessionApi(
  context: BrowserContext,
  initialRole: Role | null,
  options: { holdSecondSessionCheck?: boolean } = {},
) {
  let currentUser = initialRole ? user(initialRole) : null;
  let loginRole: Role = "doctor";
  let loginPatientId = PATIENT_A;
  let expireOnDefinition = false;
  let rejectPatientList = false;
  let endSessionOnSocket = false;
  let sessionCheckCount = 0;
  let assessmentSubmissionNetworkAvailable = true;
  const sessionCheckGate = createGate();
  const socketSessionEnd = createGate();
  const calls: ApiCall[] = [];
  const assessmentSubmissionResponses: AssessmentSubmissionResponse[] = [];
  await context.routeWebSocket("**/api/v1/ws", (socket) => {
    if (!endSessionOnSocket) {
      socket.close({ code: 1000 });
      return;
    }
    currentUser = null;
    socket.close({ code: 4401, reason: "Сессия завершена" });
    socketSessionEnd.reached();
  });
  await context.route("**/api/**", async (route) => {
    const request = route.request();
    const url = new URL(request.url());
    calls.push({
      method: request.method(),
      path: url.pathname,
      pagePath: new URL(request.frame().url()).pathname,
    });
    if (url.pathname === "/api/v1/auth/me") {
      sessionCheckCount += 1;
      if (options.holdSecondSessionCheck && sessionCheckCount === 2) {
        sessionCheckGate.reached();
        await sessionCheckGate.open;
        await expired(route);
        return;
      }
      if (currentUser) await json(route, 200, currentUser);
      else await expired(route);
      return;
    }
    if (url.pathname === "/api/v1/auth/login" && request.method() === "POST") {
      const credentials = request.postDataJSON() as { email?: string };
      if (credentials.email === "wrong@example.invalid") {
        await json(route, 401, { status: 401, title: "Неверный пароль" });
        return;
      }
      currentUser = user(loginRole, loginPatientId);
      await json(route, 200, currentUser);
      return;
    }
    if (url.pathname === "/api/v1/auth/logout" && request.method() === "POST") {
      currentUser = null;
      await route.fulfill({ status: 204, body: "" });
      return;
    }
    if (url.pathname === "/api/v1/patients" && request.method() === "GET" && rejectPatientList) {
      currentUser = null;
      await expired(route);
      return;
    }
    if (url.pathname === "/api/v1/assessments" && request.method() === "POST") {
      const { submission_id: submissionId } = request.postDataJSON() as { submission_id: string };
      if (!assessmentSubmissionNetworkAvailable) {
        assessmentSubmissionResponses.push({ submissionId, status: null });
        await route.abort("failed");
        return;
      }
      assessmentSubmissionResponses.push({ submissionId, status: 201 });
      await json(route, 201, { id: SUBMISSION_A });
      return;
    }
    if (url.pathname === "/api/v1/assessments/scales/synthetic-scale") {
      if (expireOnDefinition) {
        currentUser = null;
        await expired(route);
      } else {
        await json(route, 200, DEFINITION_V1);
      }
      return;
    }
    if (url.pathname === "/api/v1/assessments/scales") {
      await json(route, 200, { items: [DEFINITION_V1] });
      return;
    }
    if (url.pathname === "/api/v1/assessments") {
      await json(route, 200, { items: [], next_cursor: null });
      return;
    }
    if (url.pathname === "/api/v1/patients" || url.pathname === "/api/v1/alerts") {
      await json(route, 200, []);
      return;
    }
    if (/^\/api\/v1\/patients\/[^/]+\/summary$/.test(url.pathname)) {
      await json(route, 200, emptyVisitSummary());
      return;
    }
    // Главная пациента спрашивает дозы дня; без назначений карточки лекарств нет.
    if (url.pathname === "/api/v1/me/doses") {
      await json(route, 200, { day: "2026-10-18", doses: [] });
      return;
    }
    // Служебный кабинет (#56): заместители и эскалации — пустые списки.
    if (url.pathname.startsWith("/api/v1/admin/")) {
      await json(route, 200, []);
      return;
    }
    await json(route, 200, {});
  });
  return {
    calls,
    assessmentSubmissionResponses,
    setLoginRole(role: Role) {
      loginRole = role;
    },
    setLoginPatientId(patientId: string) {
      loginPatientId = patientId;
    },
    waitForHeldSessionCheck() {
      return sessionCheckGate.started;
    },
    releaseHeldSessionCheck() {
      sessionCheckGate.release();
    },
    expireOnDefinition() {
      expireOnDefinition = true;
    },
    setAssessmentSubmissionNetworkAvailable(available: boolean) {
      assessmentSubmissionNetworkAvailable = available;
    },
    rejectPatientList() {
      rejectPatientList = true;
    },
    /** The next doctor WebSocket closes with SESSION_ENDED (4401) and the session ends. */
    endSessionOnSocket(): Promise<void> {
      endSessionOnSocket = true;
      return socketSessionEnd.started;
    },
  };
}
