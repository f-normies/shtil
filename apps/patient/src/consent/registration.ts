/** Версия вида `2026-10-16-draft` показывается датой, прочие — как есть. */
export function formatConsentVersion(version: string): string {
  const match = /^(\d{4})-(\d{2})-(\d{2})/.exec(version);
  if (!match) return `Версия ${version}`;
  return `Редакция от ${match[3]}.${match[2]}.${match[1]}`;
}
